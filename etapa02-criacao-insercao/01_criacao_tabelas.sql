-- NEXUSDATA - ETAPA 02 - ENTREGAVEL 1: SQL DE CRIACAO DAS TABELAS
-- Banco: nexusdata_etapa02 | SGBD: MySQL 8.0+
--
-- Recursos de integridade usados:
--   * PRIMARY KEY simples e composta (SITUACAO_CADASTRAL, SITUACAO_DEFICIENCIA)
--   * FOREIGN KEY com ON UPDATE CASCADE em todas as referencias
--   * ON DELETE SET NULL: PESSOA.cns_principal, USUARIO.ine,
--     SITUACAO_CADASTRAL (orientacao/identidade), APURACAO_INDICADOR
--   * ON DELETE CASCADE: PARAMETRO -> CARGA
--   * CHECK: faixa dos distritos, coordenadas, sexo, CNS com 15 digitos,
--     periodo da carga, situacao cadastral, tipo de equipe, nivel territorial
--   * DEFAULT: tipo_equipe 'ESF', situacao 'ATIVO', fonte 'PEC/e-SUS APS',
--     idade_min_elegivel 11, dt_hora_extracao CURRENT_TIMESTAMP
--   * UNIQUE: CPF, login, descricoes dos dominios
--   * AUTO_INCREMENT (sequencias): ACAO_FORMATIVA, CARGA, INCONSISTENCIA,
--     GABARITO_DEFEITO, USUARIO, APURACAO_INDICADOR
--
-- ATENCAO: este script APAGA e recria as tabelas. As tabelas e visoes
-- criadas nas etapas seguintes tambem sao removidas, para que a
-- reinstalacao parta do zero.
-- =====================================================================

CREATE DATABASE IF NOT EXISTS nexusdata_etapa02
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE nexusdata_etapa02;

SET FOREIGN_KEY_CHECKS = 0;
-- Objetos das Etapas 03 a 05 (dependem das tabelas abaixo).
DROP VIEW IF EXISTS VW_EVOLUCAO_CARGAS;
DROP VIEW IF EXISTS VW_PERFIL_EQUIDADE_EQUIPE;
DROP VIEW IF EXISTS VW_LISTA_NOMINAL_INCONSISTENCIAS;
DROP TABLE IF EXISTS RESUMO_CARGA;
DROP TABLE IF EXISTS LOG_ALTERACAO_PESSOA;
-- Tabelas da Etapa 02.
DROP TABLE IF EXISTS APURACAO_INDICADOR;
DROP TABLE IF EXISTS GABARITO_DEFEITO;
DROP TABLE IF EXISTS INCONSISTENCIA;
DROP TABLE IF EXISTS SITUACAO_DEFICIENCIA;
DROP TABLE IF EXISTS SITUACAO_CADASTRAL;
DROP TABLE IF EXISTS PARAMETRO;
DROP TABLE IF EXISTS ACAO_FORMATIVA;
DROP TABLE IF EXISTS USUARIO;
DROP TABLE IF EXISTS INDICADOR;
DROP TABLE IF EXISTS POLITICA;
DROP TABLE IF EXISTS TIPO_INCONSISTENCIA;
DROP TABLE IF EXISTS TIPO_DEFICIENCIA;
DROP TABLE IF EXISTS IDENTIDADE_GENERO;
DROP TABLE IF EXISTS ORIENTACAO_SEXUAL;
DROP TABLE IF EXISTS RACA_COR;
DROP TABLE IF EXISTS PERFIL;
DROP TABLE IF EXISTS PESSOA;
DROP TABLE IF EXISTS CARGA;
DROP TABLE IF EXISTS EQUIPE;
DROP TABLE IF EXISTS UNIDADE_SAUDE;
DROP TABLE IF EXISTS DISTRITO_SANITARIO;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE DISTRITO_SANITARIO (
  id_ds TINYINT UNSIGNED PRIMARY KEY,
  nome VARCHAR(20) NOT NULL UNIQUE,
  CONSTRAINT chk_ds_faixa CHECK (id_ds BETWEEN 1 AND 8)
) ENGINE=InnoDB;

CREATE TABLE UNIDADE_SAUDE (
  cnes CHAR(7) PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  bairro VARCHAR(80) NOT NULL,
  latitude DECIMAL(9,6),
  longitude DECIMAL(9,6),
  id_ds TINYINT UNSIGNED NOT NULL,
  CONSTRAINT chk_unidade_lat CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
  CONSTRAINT chk_unidade_lon CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
  CONSTRAINT fk_unidade_distrito FOREIGN KEY (id_ds)
    REFERENCES DISTRITO_SANITARIO(id_ds)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE EQUIPE (
  ine CHAR(10) PRIMARY KEY,
  nome VARCHAR(80) NOT NULL,
  tipo_equipe VARCHAR(20) NOT NULL DEFAULT 'ESF',
  cnes CHAR(7) NOT NULL,
  CONSTRAINT chk_tipo_equipe CHECK (tipo_equipe IN ('ESF','EAP','RIBEIRINHA','OUTRA')),
  CONSTRAINT fk_equipe_unidade FOREIGN KEY (cnes)
    REFERENCES UNIDADE_SAUDE(cnes)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE ACAO_FORMATIVA (
  id_acao INT AUTO_INCREMENT PRIMARY KEY,
  ine CHAR(10) NOT NULL,
  dt_acao DATE NOT NULL,
  tipo_acao VARCHAR(80) NOT NULL,
  CONSTRAINT fk_acao_equipe FOREIGN KEY (ine)
    REFERENCES EQUIPE(ine) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE PESSOA (
  cns CHAR(15) PRIMARY KEY,
  cpf CHAR(11) UNIQUE,
  nome_civil VARCHAR(120) NOT NULL,
  dt_nascimento DATE NOT NULL,
  sexo CHAR(1) NOT NULL,
  cns_principal CHAR(15) NULL,
  CONSTRAINT chk_pessoa_sexo CHECK (sexo IN ('F','M','I')),
  CONSTRAINT chk_pessoa_cns CHECK (cns REGEXP '^[0-9]{15}$'),
  CONSTRAINT fk_pessoa_principal FOREIGN KEY (cns_principal)
    REFERENCES PESSOA(cns) ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE CARGA (
  id_carga INT AUTO_INCREMENT PRIMARY KEY,
  dt_hora_extracao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  periodo_ref_inicio DATE NOT NULL,
  periodo_ref_fim DATE NOT NULL,
  fonte VARCHAR(40) NOT NULL DEFAULT 'PEC/e-SUS APS',
  CONSTRAINT chk_periodo_carga CHECK (periodo_ref_fim >= periodo_ref_inicio)
) ENGINE=InnoDB;

CREATE TABLE RACA_COR (
  id_raca_cor TINYINT UNSIGNED PRIMARY KEY,
  descricao VARCHAR(80) NOT NULL UNIQUE,
  pop_negra BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB;

CREATE TABLE ORIENTACAO_SEXUAL (
  id_orientacao_sexual TINYINT UNSIGNED PRIMARY KEY,
  descricao VARCHAR(80) NOT NULL UNIQUE,
  publico_lgbt BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB;

CREATE TABLE IDENTIDADE_GENERO (
  id_identidade_genero TINYINT UNSIGNED PRIMARY KEY,
  descricao VARCHAR(80) NOT NULL UNIQUE,
  publico_lgbt BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB;

CREATE TABLE TIPO_DEFICIENCIA (
  id_tipo_deficiencia TINYINT UNSIGNED PRIMARY KEY,
  descricao VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE SITUACAO_CADASTRAL (
  cns CHAR(15) NOT NULL,
  id_carga INT NOT NULL,
  ine CHAR(10) NOT NULL,
  nome_social VARCHAR(120),
  id_raca_cor TINYINT UNSIGNED NOT NULL,
  deseja_informar_os BOOLEAN NOT NULL DEFAULT TRUE,
  id_orientacao_sexual TINYINT UNSIGNED NULL,
  deseja_informar_ig BOOLEAN NOT NULL DEFAULT TRUE,
  id_identidade_genero TINYINT UNSIGNED NULL,
  situacao VARCHAR(30) NOT NULL DEFAULT 'ATIVO',
  dt_atualizacao_pec DATE NOT NULL,
  PRIMARY KEY (cns, id_carga),
  CONSTRAINT chk_situacao_cad CHECK (situacao IN ('ATIVO','INATIVO','TRANSFERIDO','OBITO')),
  CONSTRAINT fk_sc_pessoa FOREIGN KEY (cns) REFERENCES PESSOA(cns)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_sc_carga FOREIGN KEY (id_carga) REFERENCES CARGA(id_carga)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_sc_equipe FOREIGN KEY (ine) REFERENCES EQUIPE(ine)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_sc_raca FOREIGN KEY (id_raca_cor) REFERENCES RACA_COR(id_raca_cor)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_sc_orientacao FOREIGN KEY (id_orientacao_sexual) REFERENCES ORIENTACAO_SEXUAL(id_orientacao_sexual)
    ON UPDATE CASCADE ON DELETE SET NULL,
  CONSTRAINT fk_sc_genero FOREIGN KEY (id_identidade_genero) REFERENCES IDENTIDADE_GENERO(id_identidade_genero)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE SITUACAO_DEFICIENCIA (
  cns CHAR(15) NOT NULL,
  id_carga INT NOT NULL,
  id_tipo_deficiencia TINYINT UNSIGNED NOT NULL,
  PRIMARY KEY (cns, id_carga, id_tipo_deficiencia),
  CONSTRAINT fk_sd_situacao FOREIGN KEY (cns, id_carga)
    REFERENCES SITUACAO_CADASTRAL(cns, id_carga)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_sd_tipo FOREIGN KEY (id_tipo_deficiencia)
    REFERENCES TIPO_DEFICIENCIA(id_tipo_deficiencia)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE PARAMETRO (
  id_carga INT PRIMARY KEY,
  idade_min_elegivel TINYINT UNSIGNED NOT NULL DEFAULT 11,
  CONSTRAINT chk_idade_min CHECK (idade_min_elegivel BETWEEN 0 AND 120),
  CONSTRAINT fk_parametro_carga FOREIGN KEY (id_carga)
    REFERENCES CARGA(id_carga) ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE TIPO_INCONSISTENCIA (
  id_tipo_inconsistencia TINYINT UNSIGNED PRIMARY KEY,
  descricao VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE INCONSISTENCIA (
  id_inconsistencia BIGINT AUTO_INCREMENT PRIMARY KEY,
  ine_responsavel CHAR(10) NOT NULL,
  cns CHAR(15) NOT NULL,
  id_carga INT NOT NULL,
  campo VARCHAR(80) NOT NULL,
  id_tipo_inconsistencia TINYINT UNSIGNED NOT NULL,
  CONSTRAINT fk_inc_equipe FOREIGN KEY (ine_responsavel) REFERENCES EQUIPE(ine)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_inc_pessoa FOREIGN KEY (cns) REFERENCES PESSOA(cns)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_inc_carga FOREIGN KEY (id_carga) REFERENCES CARGA(id_carga)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_inc_tipo FOREIGN KEY (id_tipo_inconsistencia) REFERENCES TIPO_INCONSISTENCIA(id_tipo_inconsistencia)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE GABARITO_DEFEITO (
  id_defeito BIGINT AUTO_INCREMENT PRIMARY KEY,
  cns CHAR(15) NOT NULL,
  id_carga INT NOT NULL,
  campo VARCHAR(80) NOT NULL,
  id_tipo_inconsistencia TINYINT UNSIGNED NOT NULL,
  CONSTRAINT fk_gd_pessoa FOREIGN KEY (cns) REFERENCES PESSOA(cns)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_gd_carga FOREIGN KEY (id_carga) REFERENCES CARGA(id_carga)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_gd_tipo FOREIGN KEY (id_tipo_inconsistencia) REFERENCES TIPO_INCONSISTENCIA(id_tipo_inconsistencia)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE PERFIL (
  id_perfil TINYINT UNSIGNED PRIMARY KEY,
  nome VARCHAR(40) NOT NULL UNIQUE,
  abrangencia VARCHAR(40) NOT NULL DEFAULT 'TERRITORIO',
  CONSTRAINT chk_perfil_abrangencia CHECK (abrangencia IN ('TERRITORIO','MUNICIPIO','UNIDADE','EQUIPE'))
) ENGINE=InnoDB;

CREATE TABLE USUARIO (
  id_usuario INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  login VARCHAR(80) NOT NULL UNIQUE,
  id_perfil TINYINT UNSIGNED NOT NULL,
  ine CHAR(10) NULL,
  CONSTRAINT fk_usuario_perfil FOREIGN KEY (id_perfil) REFERENCES PERFIL(id_perfil)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_usuario_equipe FOREIGN KEY (ine) REFERENCES EQUIPE(ine)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE POLITICA (
  id_politica TINYINT UNSIGNED PRIMARY KEY,
  nome VARCHAR(120) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE INDICADOR (
  id_indicador SMALLINT UNSIGNED PRIMARY KEY,
  nome VARCHAR(120) NOT NULL UNIQUE,
  descricao TEXT NOT NULL,
  formula_calculo TEXT NOT NULL,
  id_politica TINYINT UNSIGNED NOT NULL,
  CONSTRAINT fk_ind_politica FOREIGN KEY (id_politica) REFERENCES POLITICA(id_politica)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE APURACAO_INDICADOR (
  id_apuracao BIGINT AUTO_INCREMENT PRIMARY KEY,
  id_indicador SMALLINT UNSIGNED NOT NULL,
  id_carga INT NOT NULL,
  nivel_territorial VARCHAR(30) NOT NULL,
  id_ds TINYINT UNSIGNED NULL,
  cnes CHAR(7) NULL,
  ine CHAR(10) NULL,
  numerador INT UNSIGNED NOT NULL DEFAULT 0,
  denominador INT UNSIGNED NOT NULL DEFAULT 0,
  valor DECIMAL(10,4),
  CONSTRAINT chk_nivel_territorial CHECK (nivel_territorial IN ('MUNICIPIO','DISTRITO','UNIDADE','EQUIPE')),
  CONSTRAINT chk_apuracao_valor CHECK (valor IS NULL OR valor >= 0),
  CONSTRAINT fk_ap_indicador FOREIGN KEY (id_indicador) REFERENCES INDICADOR(id_indicador)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_ap_carga FOREIGN KEY (id_carga) REFERENCES CARGA(id_carga)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_ap_distrito FOREIGN KEY (id_ds) REFERENCES DISTRITO_SANITARIO(id_ds)
    ON UPDATE CASCADE ON DELETE SET NULL,
  CONSTRAINT fk_ap_unidade FOREIGN KEY (cnes) REFERENCES UNIDADE_SAUDE(cnes)
    ON UPDATE CASCADE ON DELETE SET NULL,
  CONSTRAINT fk_ap_equipe FOREIGN KEY (ine) REFERENCES EQUIPE(ine)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;
